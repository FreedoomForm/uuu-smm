const UI: Record<Lang, Dict> = { en, ru, uz };

export function tUI(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const dict = UI[lang] || UI.en;
  let s = dict[key] ?? UI.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

// --- Question/answer translation helpers (DB stores Question.translations) ---

export function qtr(q: any, lang: Lang): QTranslations | undefined {
  return q?.translations?.[lang];
}

export function trText(q: any, lang: Lang): string {
  return qtr(q, lang)?.text || q?.text || '';
}

export function trOption(q: any, letter: string, lang: Lang): string {
  return qtr(q, lang)?.options?.[letter] || q?.[`option${letter}`] || '';
}

export function trExpl(q: any, lang: Lang, fetched?: string): string | undefined {
  return qtr(q, lang)?.explanation || fetched || undefined;
}
